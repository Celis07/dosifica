function fraseDelDia(fecha){
  const iso = fecha || todayISO();
  const d = new Date(iso + 'T12:00:00'), ini = new Date(iso.slice(0, 4) + '-01-01T12:00:00');
  const doy = Math.round((d - ini) / 864e5) + d.getFullYear() * 7;   // cambia cada día y no repite el mismo orden cada año
  return FRASES[((doy % FRASES.length) + FRASES.length) % FRASES.length];
}
